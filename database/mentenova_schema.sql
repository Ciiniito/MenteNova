BEGIN;

CREATE TABLE rol (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(150),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol SMALLINT NOT NULL REFERENCES rol(id_rol) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_usuario_correo_ci ON usuario (LOWER(correo));

CREATE TABLE paciente (
    id_paciente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT UNIQUE REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE SET NULL,
    tipo_documento VARCHAR(10),
    numero_documento VARCHAR(20),
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(254),
    direccion VARCHAR(250),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_paciente_documento CHECK (
        (numero_documento IS NULL AND tipo_documento IS NULL)
        OR (numero_documento IS NOT NULL AND tipo_documento IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_paciente_documento
    ON paciente (tipo_documento, numero_documento)
    WHERE numero_documento IS NOT NULL;

CREATE TABLE psicologo (
    id_psicologo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    numero_colegiatura VARCHAR(30) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE especialidad (
    id_especialidad SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(250),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE psicologo_especialidad (
    id_psicologo BIGINT NOT NULL REFERENCES psicologo(id_psicologo) ON UPDATE CASCADE ON DELETE CASCADE,
    id_especialidad SMALLINT NOT NULL REFERENCES especialidad(id_especialidad) ON UPDATE CASCADE ON DELETE RESTRICT,
    PRIMARY KEY (id_psicologo, id_especialidad)
);

CREATE TABLE disponibilidad (
    id_disponibilidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_psicologo BIGINT NOT NULL REFERENCES psicologo(id_psicologo) ON UPDATE CASCADE ON DELETE RESTRICT,
    dia_semana SMALLINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    modalidad VARCHAR(12) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_disponibilidad_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_disponibilidad_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_disponibilidad_modalidad CHECK (modalidad IN ('PRESENCIAL','VIRTUAL')),
    CONSTRAINT uq_disponibilidad UNIQUE (id_psicologo, dia_semana, hora_inicio, hora_fin, modalidad)
);

CREATE TABLE excepcion_disponibilidad (
    id_excepcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_psicologo BIGINT NOT NULL REFERENCES psicologo(id_psicologo) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    tipo VARCHAR(15) NOT NULL,
    motivo VARCHAR(250),
    CONSTRAINT ck_excepcion_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_excepcion_tipo CHECK (tipo IN ('BLOQUEO','HABILITACION'))
);

CREATE TABLE estado_cita (
    id_estado_cita SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(150),
    es_final BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE cita (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_psicologo BIGINT NOT NULL REFERENCES psicologo(id_psicologo) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_estado_cita SMALLINT NOT NULL REFERENCES estado_cita(id_estado_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    modalidad VARCHAR(12) NOT NULL,
    motivo_administrativo VARCHAR(250),
    observacion VARCHAR(500),
    creado_por BIGINT NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cita_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_cita_modalidad CHECK (modalidad IN ('PRESENCIAL','VIRTUAL'))
);

CREATE TABLE historial_cita (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    tipo_evento VARCHAR(30) NOT NULL,
    id_estado_anterior SMALLINT REFERENCES estado_cita(id_estado_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_estado_nuevo SMALLINT REFERENCES estado_cita(id_estado_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_anterior DATE,
    hora_anterior TIME,
    fecha_nueva DATE,
    hora_nueva TIME,
    motivo VARCHAR(250),
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_historial_tipo CHECK (
        tipo_evento IN ('CREADA','CONFIRMADA','REPROGRAMADA','CANCELADA','ATENDIDA','NO_ASISTIO','CAMBIO_ESTADO')
    )
);

CREATE TABLE atencion (
    id_atencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL UNIQUE REFERENCES cita(id_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    atendido BOOLEAN NOT NULL,
    observacion_administrativa VARCHAR(500),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    monto NUMERIC(10,2) NOT NULL,
    medio_pago VARCHAR(20) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    fecha_pago TIMESTAMPTZ,
    numero_operacion VARCHAR(50),
    registrado_por BIGINT NOT NULL REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pago_monto CHECK (monto >= 0),
    CONSTRAINT ck_pago_medio CHECK (medio_pago IN ('EFECTIVO','TARJETA','TRANSFERENCIA','YAPE','PLIN','OTRO')),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('PENDIENTE','PAGADO','ANULADO'))
);

CREATE TABLE notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL REFERENCES cita(id_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    tipo VARCHAR(30) NOT NULL,
    canal VARCHAR(20) NOT NULL,
    fecha_programada TIMESTAMPTZ,
    fecha_envio TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    destinatario VARCHAR(254),
    mensaje TEXT,
    CONSTRAINT ck_notificacion_tipo CHECK (tipo IN ('CONFIRMACION','RECORDATORIO','REPROGRAMACION','CANCELACION')),
    CONSTRAINT ck_notificacion_canal CHECK (canal IN ('CORREO','SISTEMA')),
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('PENDIENTE','ENVIADA','ERROR','CANCELADA'))
);

CREATE TABLE auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE SET NULL,
    entidad VARCHAR(50) NOT NULL,
    id_entidad BIGINT NOT NULL,
    accion VARCHAR(20) NOT NULL,
    valor_anterior JSONB,
    valor_nuevo JSONB,
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_auditoria_accion CHECK (accion IN ('INSERT','UPDATE','DELETE','LOGIN','CAMBIO_ESTADO'))
);

