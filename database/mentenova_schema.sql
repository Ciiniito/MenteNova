-- Actualizacion automatica de fecha_actualizacion
CREATE OR REPLACE FUNCTION fn_set_fecha_actualizacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuario_fecha_actualizacion
BEFORE UPDATE ON usuario
FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_actualizacion();

CREATE TRIGGER trg_cita_fecha_actualizacion
BEFORE UPDATE ON cita
FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_actualizacion();

-- Regla anti-solapamiento para citas activas del mismo psicologo.
CREATE OR REPLACE FUNCTION fn_validar_solapamiento_cita()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM cita c
        JOIN estado_cita ec ON ec.id_estado_cita = c.id_estado_cita
        WHERE c.id_psicologo = NEW.id_psicologo
          AND c.fecha = NEW.fecha
          AND c.id_cita <> COALESCE(NEW.id_cita, 0)
          AND ec.codigo IN ('PENDIENTE','CONFIRMADA')
          AND NEW.hora_inicio < c.hora_fin
          AND NEW.hora_fin > c.hora_inicio
    ) THEN
        RAISE EXCEPTION 'El psicologo ya posee una cita activa que se solapa con el horario solicitado';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cita_anti_solapamiento
BEFORE INSERT OR UPDATE OF id_psicologo, fecha, hora_inicio, hora_fin, id_estado_cita
ON cita
FOR EACH ROW EXECUTE FUNCTION fn_validar_solapamiento_cita();

-- Auditoria automatica de cambios de CITA. La aplicacion puede establecer:
-- SET LOCAL app.user_id = '123';
CREATE OR REPLACE FUNCTION fn_auditar_cita()
RETURNS TRIGGER AS $$
DECLARE
    v_usuario BIGINT;
    v_id BIGINT;
BEGIN
    BEGIN
        v_usuario := NULLIF(current_setting('app.user_id', true), '')::BIGINT;
    EXCEPTION WHEN OTHERS THEN
        v_usuario := NULL;
    END;

    v_id := COALESCE(NEW.id_cita, OLD.id_cita);

    INSERT INTO auditoria(id_usuario, entidad, id_entidad, accion, valor_anterior, valor_nuevo)
    VALUES (
        v_usuario,
        'cita',
        v_id,
        TG_OP,
        CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) ELSE NULL END,
        CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) ELSE NULL END
    );

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_auditoria_cita
AFTER INSERT OR UPDATE OR DELETE ON cita
FOR EACH ROW EXECUTE FUNCTION fn_auditar_cita();

